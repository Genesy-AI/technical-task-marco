// Common non-ISO codes mapped to their official ISO code.
const ALIASES: Readonly<Record<string, string>> = {
  UK: 'GB',
}

export interface CountryCodeResult {
  /** Normalized ISO alpha-2 code, or null when empty or invalid. */
  code: string | null
  /** True when a non-empty value was provided but is not a valid code. */
  invalid: boolean
}

/**
 * Normalizes an optional country code: trims, uppercases, maps aliases (UK -> GB)
 * and validates against ISO 3166-1 alpha-2. Empty input is valid (field is optional).
 */
export const normalizeCountryCode = (raw: unknown): CountryCodeResult => {
  if (raw === undefined || raw === null) return { code: null, invalid: false }
  if (typeof raw !== 'string') return { code: null, invalid: true }

  const upper = raw.trim().toUpperCase()
  if (!upper) return { code: null, invalid: false }

  const candidate = ALIASES[upper] ?? upper
  return ISO_ALPHA2_CODES.has(candidate) ? { code: candidate, invalid: false } : { code: null, invalid: true }
}
